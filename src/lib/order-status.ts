export type Status =
  | "DRAFT"
  | "PENDING_CONFIRMATION"
  | "NEEDS_INFO"
  | "AWAITING_CUSTOMER"
  | "CONFIRMED"
  | "SHIPMENT_PENDING"
  | "SHIPMENT_UNKNOWN"
  | "SHIPPED"
  | "OUT_FOR_DELIVERY"
  | "DELIVERED"
  | "CASH_COLLECTED"
  | "RETURNED"
  | "CANCELLED"
  | "EXPIRED"
  | "FAILED";

// Allowed state transitions across the full Algerian COD lifecycle
const MOVES: Partial<Record<Status, Status[]>> = {
  DRAFT: ["PENDING_CONFIRMATION", "CONFIRMED", "NEEDS_INFO", "AWAITING_CUSTOMER", "CANCELLED", "EXPIRED"],
  PENDING_CONFIRMATION: ["CONFIRMED", "NEEDS_INFO", "AWAITING_CUSTOMER", "CANCELLED"],
  NEEDS_INFO: ["PENDING_CONFIRMATION", "CONFIRMED", "AWAITING_CUSTOMER", "CANCELLED"],
  AWAITING_CUSTOMER: ["PENDING_CONFIRMATION", "CONFIRMED", "CANCELLED"],
  CONFIRMED: ["SHIPMENT_PENDING", "CANCELLED"],
  SHIPMENT_PENDING: ["SHIPPED", "CONFIRMED", "SHIPMENT_UNKNOWN"],
  SHIPMENT_UNKNOWN: ["SHIPPED", "CONFIRMED", "CANCELLED"],
  SHIPPED: ["OUT_FOR_DELIVERY", "DELIVERED", "RETURNED", "FAILED"],
  OUT_FOR_DELIVERY: ["DELIVERED", "RETURNED", "FAILED"],
  DELIVERED: ["CASH_COLLECTED", "RETURNED"],
};

export const canTransition = (from: Status, to: Status) => (MOVES[from] ?? []).includes(to);

export const allowedFrom = (to: Status): Status[] =>
  (Object.keys(MOVES) as Status[]).filter((f) => canTransition(f, to));
